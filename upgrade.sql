USE chatwave;
ALTER TABLE users ADD COLUMN IF NOT EXISTS username VARCHAR(40) NULL UNIQUE;
ALTER TABLE users ADD COLUMN IF NOT EXISTS description VARCHAR(280) NULL;
ALTER TABLE users ADD COLUMN IF NOT EXISTS role ENUM('user','admin') NOT NULL DEFAULT 'user';
ALTER TABLE users ADD COLUMN IF NOT EXISTS account_status ENUM('active','frozen','banned') NOT NULL DEFAULT 'active';
ALTER TABLE users ADD COLUMN IF NOT EXISTS read_receipts TINYINT(1) NOT NULL DEFAULT 1;
ALTER TABLE users ADD COLUMN IF NOT EXISTS status_visibility ENUM('everyone','contacts','nobody') NOT NULL DEFAULT 'contacts';
ALTER TABLE users ADD COLUMN IF NOT EXISTS online_visibility ENUM('everyone','contacts','nobody') NOT NULL DEFAULT 'everyone';
ALTER TABLE users ADD COLUMN IF NOT EXISTS away_message VARCHAR(180) NULL;
ALTER TABLE users ADD COLUMN IF NOT EXISTS last_active DATETIME NULL;

CREATE TABLE IF NOT EXISTS recovery_codes (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 code_hash CHAR(64) NOT NULL,
 expires_at DATETIME NOT NULL,
 attempts TINYINT UNSIGNED NOT NULL DEFAULT 0,
 used_at DATETIME NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_recovery_user (user_id, created_at),
 CONSTRAINT fk_recovery_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS chat_groups (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(80) NOT NULL,
 description VARCHAR(250) NULL,
 created_by BIGINT UNSIGNED NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_group_creator FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS group_members (
 group_id BIGINT UNSIGNED NOT NULL,
 user_id BIGINT UNSIGNED NOT NULL,
 member_role ENUM('admin','member') NOT NULL DEFAULT 'member',
 joined_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY (group_id,user_id),
 CONSTRAINT fk_gm_group FOREIGN KEY (group_id) REFERENCES chat_groups(id) ON DELETE CASCADE,
 CONSTRAINT fk_gm_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS group_messages (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 group_id BIGINT UNSIGNED NOT NULL,
 sender_id BIGINT UNSIGNED NOT NULL,
 body VARCHAR(4000) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_group_messages (group_id,id),
 CONSTRAINT fk_gmsg_group FOREIGN KEY (group_id) REFERENCES chat_groups(id) ON DELETE CASCADE,
 CONSTRAINT fk_gmsg_sender FOREIGN KEY (sender_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS statuses (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 caption VARCHAR(500) NULL,
 media_path VARCHAR(255) NULL,
 media_mime VARCHAR(100) NULL,
 expires_at DATETIME NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_status_expiry (expires_at,user_id),
 CONSTRAINT fk_status_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS status_reactions (
 status_id BIGINT UNSIGNED NOT NULL,
 user_id BIGINT UNSIGNED NOT NULL,
 reaction ENUM('like') NOT NULL DEFAULT 'like',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY (status_id,user_id),
 CONSTRAINT fk_sr_status FOREIGN KEY (status_id) REFERENCES statuses(id) ON DELETE CASCADE,
 CONSTRAINT fk_sr_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS status_reshares (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 status_id BIGINT UNSIGNED NOT NULL,
 user_id BIGINT UNSIGNED NOT NULL,
 caption VARCHAR(500) NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uq_status_reshare (status_id,user_id),
 CONSTRAINT fk_srs_status FOREIGN KEY (status_id) REFERENCES statuses(id) ON DELETE CASCADE,
 CONSTRAINT fk_srs_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS admin_actions (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 admin_id BIGINT UNSIGNED NOT NULL,
 target_user_id BIGINT UNSIGNED NOT NULL,
 action ENUM('freeze','unfreeze','ban','unban') NOT NULL,
 reason VARCHAR(255) NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_admin_action_admin FOREIGN KEY (admin_id) REFERENCES users(id) ON DELETE CASCADE,
 CONSTRAINT fk_admin_action_target FOREIGN KEY (target_user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
