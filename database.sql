CREATE DATABASE IF NOT EXISTS chatwave CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE chatwave;

CREATE TABLE IF NOT EXISTS users (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(60) NOT NULL,
  email VARCHAR(190) NOT NULL UNIQUE,
  phone_number VARCHAR(30) NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  last_seen DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS messages (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  sender_id BIGINT UNSIGNED NOT NULL,
  receiver_id BIGINT UNSIGNED NOT NULL,
  body VARCHAR(4000) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_conversation (sender_id, receiver_id, id),
  INDEX idx_receiver (receiver_id, id),
  CONSTRAINT fk_messages_sender FOREIGN KEY (sender_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_messages_receiver FOREIGN KEY (receiver_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;


ALTER TABLE users
  ADD COLUMN IF NOT EXISTS phone_number VARCHAR(30) NULL UNIQUE,
  ADD COLUMN IF NOT EXISTS profile_image VARCHAR(255) NULL;

ALTER TABLE messages
  ADD COLUMN IF NOT EXISTS attachment_path VARCHAR(255) NULL,
  ADD COLUMN IF NOT EXISTS attachment_name VARCHAR(255) NULL,
  ADD COLUMN IF NOT EXISTS attachment_mime VARCHAR(100) NULL,
  ADD COLUMN IF NOT EXISTS read_at DATETIME NULL;

CREATE TABLE IF NOT EXISTS call_signals (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  call_key VARCHAR(100) NOT NULL,
  sender_id BIGINT UNSIGNED NOT NULL,
  receiver_id BIGINT UNSIGNED NOT NULL,
  signal_type VARCHAR(30) NOT NULL,
  payload MEDIUMTEXT NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_call_receiver (receiver_id, call_key, id),
  CONSTRAINT fk_signal_sender FOREIGN KEY (sender_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_signal_receiver FOREIGN KEY (receiver_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
